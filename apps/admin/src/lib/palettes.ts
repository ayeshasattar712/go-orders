export function getPalette(id: string): ColorPalette {
  return colorPalettes.find((palette) => palette.id === id) ?? colorPalettes[0]!;
}

/**
 * Vars that carry a palette's accent identity (buttons, links, hero gradient, charts).
 * Everything else (page/card/sidebar background, text, borders) is intentionally left
 * alone so the storefront always stays on its light base, even for "dark" palettes.
 */
const ACCENT_VAR_NAMES = new Set([
  '--primary',
  '--primary-foreground',
  '--accent-brand',
  '--accent-brand-foreground',
  '--ring',
  '--sidebar-accent',
  '--gradient-hero-from',
  '--gradient-hero-via',
  '--gradient-hero-to',
  '--chart-1',
  '--chart-2',
  '--chart-3',
]);

/** Applies (or clears, for the default palette) a palette's accent-color overrides on :root. */
export function applyPalette(id: string) {
  if (typeof document === 'undefined') return;
  const root = document.documentElement.style;
  const palette = getPalette(id);
  for (const name of ACCENT_VAR_NAMES) {
    const value = palette.vars[name];
    if (value) root.setProperty(name, value);
    else root.removeProperty(name);
  }
  document.documentElement.setAttribute('data-palette-mode', 'light');
}
